// Package pipelinetest runs the real pipeline over the fixture PRs #101–#104
// with a caller-supplied Jev client. It is the single code path for Jev
// recordings (tools/recordjev wraps the client in jev.Recorder) and for the
// replay tests (jev.Replay), so request bytes match by construction
// (DECISIONS "M1 Jev recordings flow").
//
// It deliberately has no testing import so the recorder tool can use it.
// Everything that shapes a request is fixed: the generated fixture repo
// (deterministic SHAs), the offline GitHub fixture, the repo-local config
// only (never XDG or env), the built-in question catalogue, a fixed clock
// and a fresh in-memory store. PRs run one after another in number order.
// The embedder (WithEmbedder) is the caller's: pair requests depend on its
// candidates, so a recording run and its replay must use the same one.
package pipelinetest

import (
	"context"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"time"

	"github.com/charmbracelet/log"

	"github.com/fredricw/prt/internal/config"
	"github.com/fredricw/prt/internal/embed"
	"github.com/fredricw/prt/internal/gh"
	"github.com/fredricw/prt/internal/gitx"
	"github.com/fredricw/prt/internal/jev"
	"github.com/fredricw/prt/internal/model"
	"github.com/fredricw/prt/internal/pipeline"
	"github.com/fredricw/prt/internal/questions"
	"github.com/fredricw/prt/internal/store"
)

// Now is the fixed clock of fixture runs.
var Now = time.Date(2026, 10, 13, 12, 0, 0, 0, time.UTC)

// PRNumbers are the fixture PRs run, in order.
var PRNumbers = []int{101, 102, 103, 104}

// Outcome is everything one fixture PR's run stored.
type Outcome struct {
	Item  model.Item
	Files []model.File
	Units []model.ChangeUnit
	// Labels are the stored labels of the units and of the item subject.
	Labels []model.Label
	// Links are the stored links (structural, Jev-confirmed, mechanical
	// candidates) and Groups the stored groups, in review order.
	Links   []model.Link
	Groups  []model.Group
	Agg     model.ItemAgg
	RunLogs []model.RunLog
}

// Failed returns the RunLog rows of stages that failed (empty when the run
// was clean). A Jev failure is soft in the pipeline, so callers that need
// labels must check this, not only the error of FixtureRun.
func (o Outcome) Failed() []model.RunLog {
	var out []model.RunLog
	for _, rl := range o.RunLogs {
		if rl.Status == model.StageFailed {
			out = append(out, rl)
		}
	}
	return out
}

// Option tunes a fixture run without changing its requests.
type Option func(*options)

type options struct {
	log      *log.Logger
	emit     func(model.RunLog)
	embedder embed.Embedder
}

// WithLogger sets the pipeline logger (default: discard).
func WithLogger(l *log.Logger) Option { return func(o *options) { o.log = l } }

// WithEmbedder sets the stage-3 embedder (default nil: stage 3 is skipped
// and only mechanical candidates and structural links group units). Use
// embed.Replay over testdata/recordings/embed for recorded vectors; pair
// requests (and so Jev recordings) depend on the embed candidates, so a
// Jev recording run and its replay must use the same embedder.
func WithEmbedder(e embed.Embedder) Option { return func(o *options) { o.embedder = e } }

// WithEmit receives every RunLog row as stages start and finish.
func WithEmit(fn func(model.RunLog)) Option { return func(o *options) { o.emit = fn } }

// FixtureRun runs every built stage (fetch → parse → link → embed → jev →
// cluster → aggregate) for PRs #101–#104 of the
// fixture repo at repoDir (generated by internal/fixturegen), using the
// GitHub fixture prsJSON (testdata/fixtures/prs.json) and Jev client jc. It
// returns an error for setup failures and hard (fetch/parse/aggregate)
// failures; a failed Jev stage is reported in Outcome.RunLogs.
func FixtureRun(ctx context.Context, repoDir, prsJSON string, jc jev.Client, opts ...Option) (map[int]Outcome, error) {
	o := options{log: log.New(io.Discard)}
	for _, fn := range opts {
		fn(&o)
	}
	d, closeFn, err := fixtureDeps(ctx, repoDir, prsJSON, jc, o)
	if err != nil {
		return nil, err
	}
	defer closeFn()
	prs, err := loadPRs(prsJSON)
	if err != nil {
		return nil, err
	}
	p := pipeline.New(d)
	out := make(map[int]Outcome, len(PRNumbers))
	for _, n := range PRNumbers {
		pr, ok := prs[n]
		if !ok {
			return nil, fmt.Errorf("pipelinetest: PR #%d not in %s", n, prsJSON)
		}
		oc, err := runPR(ctx, p, d.Store, pr)
		if err != nil {
			return out, err
		}
		out[n] = oc
	}
	return out, nil
}

// fixtureDeps builds the fixed pipeline dependencies for a fixture repo.
func fixtureDeps(ctx context.Context, repoDir, prsJSON string, jc jev.Client, o options) (pipeline.Deps, func(), error) {
	g, err := gitx.Open(ctx, repoDir)
	if err != nil {
		return pipeline.Deps{}, nil, fmt.Errorf("pipelinetest: open repo: %w", err)
	}
	gitDir, err := g.GitDir(ctx)
	if err != nil {
		return pipeline.Deps{}, nil, fmt.Errorf("pipelinetest: git dir: %w", err)
	}
	cfg, err := config.Load([]string{filepath.Join(gitDir, "prt")})
	if err != nil {
		return pipeline.Deps{}, nil, fmt.Errorf("pipelinetest: config: %w", err)
	}
	fake, err := gh.LoadFixture(prsJSON)
	if err != nil {
		return pipeline.Deps{}, nil, fmt.Errorf("pipelinetest: %w", err)
	}
	st, err := store.OpenMemory(ctx)
	if err != nil {
		return pipeline.Deps{}, nil, fmt.Errorf("pipelinetest: store: %w", err)
	}
	d := pipeline.Deps{
		Git: g, GH: fake, Jev: jc, Embedder: o.embedder, Store: st, Config: cfg, Routing: config.DefaultRouting(),
		Questions: questions.Default(), Log: o.log, Emit: o.emit,
		Now: func() time.Time { return Now },
	}
	return d, func() { _ = st.Close() }, nil
}

// loadPRs reads the PR list of a GitHub fixture file, keyed by number.
func loadPRs(path string) (map[int]gh.PR, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("pipelinetest: read %s: %w", path, err)
	}
	var fx gh.Fixture
	if err := json.Unmarshal(b, &fx); err != nil {
		return nil, fmt.Errorf("pipelinetest: decode %s: %w", path, err)
	}
	out := make(map[int]gh.PR, len(fx.PRs))
	for _, pr := range fx.PRs {
		out[pr.Number] = pr
	}
	return out, nil
}

// itemFor builds the stored item of a fixture PR.
func itemFor(pr gh.PR) model.Item {
	return model.Item{
		ID: model.PRItemID(pr.Number), Kind: model.KindPR, Number: pr.Number,
		Ref: pr.HeadRef, BaseRef: pr.BaseRef, HeadSHA: pr.HeadSHA,
		Title: pr.Title, Body: pr.Body, Author: pr.Author, Reviewers: pr.Reviewers,
		CI: pr.CI, Labels: pr.Labels, URL: pr.URL, Source: model.SourceRanked,
		CreatedAt: pr.CreatedAt, UpdatedAt: pr.UpdatedAt, Draft: pr.Draft,
		ReviewRequested: pr.ReviewRequested, ViewerApproved: pr.ViewerApproved,
	}
}

// runPR stores the PR's item, runs the pipeline and collects the outcome.
func runPR(ctx context.Context, p *pipeline.Pipeline, st store.Store, pr gh.PR) (Outcome, error) {
	it := itemFor(pr)
	if err := st.UpsertItem(ctx, it); err != nil {
		return Outcome{}, fmt.Errorf("pipelinetest: store #%d: %w", pr.Number, err)
	}
	if err := p.Run(ctx, it); err != nil {
		return Outcome{}, fmt.Errorf("pipelinetest: run #%d: %w", pr.Number, err)
	}
	return collect(ctx, st, it.ID)
}

// collect reads back what the run stored for an item.
func collect(ctx context.Context, st store.Store, id string) (Outcome, error) {
	var o Outcome
	var err error
	if o.Item, err = st.Item(ctx, id); err != nil {
		return o, fmt.Errorf("pipelinetest: item %s: %w", id, err)
	}
	if o.Files, err = st.Files(ctx, id); err != nil {
		return o, fmt.Errorf("pipelinetest: files %s: %w", id, err)
	}
	if o.Units, err = st.Units(ctx, id); err != nil {
		return o, fmt.Errorf("pipelinetest: units %s: %w", id, err)
	}
	ids := []string{model.ItemSubject(id)}
	for _, u := range o.Units {
		ids = append(ids, u.ID)
	}
	if o.Labels, err = st.Labels(ctx, ids); err != nil {
		return o, fmt.Errorf("pipelinetest: labels %s: %w", id, err)
	}
	SortLabels(o.Labels)
	if o.Links, err = st.Links(ctx, id); err != nil {
		return o, fmt.Errorf("pipelinetest: links %s: %w", id, err)
	}
	if o.Groups, err = st.Groups(ctx, id); err != nil {
		return o, fmt.Errorf("pipelinetest: groups %s: %w", id, err)
	}
	agg, ok, err := st.Agg(ctx, id)
	if err != nil {
		return o, fmt.Errorf("pipelinetest: agg %s: %w", id, err)
	}
	if !ok {
		return o, fmt.Errorf("pipelinetest: agg %s: not stored", id)
	}
	o.Agg = agg
	if o.RunLogs, err = st.RunLogs(ctx, id); err != nil {
		return o, fmt.Errorf("pipelinetest: run logs %s: %w", id, err)
	}
	return o, nil
}

// SortLabels orders labels by unit, question and line, so outcomes of two
// runs compare equal regardless of store order.
func SortLabels(ls []model.Label) {
	sort.SliceStable(ls, func(i, j int) bool {
		a, b := ls[i], ls[j]
		if a.UnitID != b.UnitID {
			return a.UnitID < b.UnitID
		}
		if a.Question != b.Question {
			return a.Question < b.Question
		}
		return a.Line < b.Line
	})
}
